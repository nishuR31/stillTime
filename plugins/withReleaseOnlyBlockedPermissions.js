/**
 * Strips dev-only permissions from the **release** build.
 *
 * `android.blockedPermissions` in `app.config.ts` emits `tools:node="remove"`
 * into `app/src/main/AndroidManifest.xml`, which applies to every variant. That
 * is too blunt for anything the development server needs:
 *
 *   - `INTERNET` / `ACCESS_NETWORK_STATE` — a debug APK connects to the Metro
 *     dev server on `localhost:8081`. Without these, `bun run android` installs
 *     an app that can never load a bundle.
 *   - `SYSTEM_ALERT_WINDOW` — Expo's debug manifest requests it for the dev
 *     menu and the red-box overlay.
 *
 * Manifest-merge priority is variant > main > libraries, so writing the same
 * `tools:node="remove"` markers into `app/src/release/AndroidManifest.xml`
 * blocks the permission where it matters (a shipped APK) and leaves debug
 * builds fully functional.
 *
 * The list here is the source of truth; do not also put these in
 * `blockedPermissions`, which would strip them from every variant again.
 *
 * CommonJS on purpose: see the note in `./gradleReference.js`.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const { createRunOncePlugin, withDangerousMod } = require('expo/config-plugins');

/** Permissions a shipped APK must never carry, but a debug build needs. */
const RELEASE_ONLY_BLOCKED = [
  'android.permission.INTERNET',
  'android.permission.ACCESS_NETWORK_STATE',
  'android.permission.SYSTEM_ALERT_WINDOW',
];

const MANIFEST_HEADER = [
  '<?xml version="1.0" encoding="utf-8"?>',
  '<!--',
  '  Generated by `plugins/withReleaseOnlyBlockedPermissions.js` during',
  '  `expo prebuild`. Do not edit: `android/` is git-ignored and regenerated.',
  '-->',
  '<manifest xmlns:android="http://schemas.android.com/apk/res/android"',
  '    xmlns:tools="http://schemas.android.com/tools">',
];

/** @param {readonly string[]} permissions */
function renderManifest(permissions) {
  const entries = permissions.map(
    (permission) => `  <uses-permission android:name="${permission}" tools:node="remove" />`,
  );
  return `${[...MANIFEST_HEADER, ...entries, '</manifest>', ''].join('\n')}`;
}

const withReleaseOnlyBlockedPermissions = createRunOncePlugin(
  (config) =>
    withDangerousMod(config, [
      'android',
      async (cfg) => {
        const releaseDir = path.join(
          cfg.modRequest.platformProjectRoot,
          'app',
          'src',
          'release',
        );
        fs.mkdirSync(releaseDir, { recursive: true });
        fs.writeFileSync(
          path.join(releaseDir, 'AndroidManifest.xml'),
          renderManifest(RELEASE_ONLY_BLOCKED),
          'utf8',
        );

        console.log(`[stilltime] Release-only permission block: ${RELEASE_ONLY_BLOCKED.join(', ')}`);
        return cfg;
      },
    ]),
  'withReleaseOnlyBlockedPermissions',
  '1.0.0',
);

module.exports = withReleaseOnlyBlockedPermissions;
module.exports.default = withReleaseOnlyBlockedPermissions;
module.exports.RELEASE_ONLY_BLOCKED = RELEASE_ONLY_BLOCKED;
module.exports.renderManifest = renderManifest;
